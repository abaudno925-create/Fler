/* Dumps the offsets of the running game into a C++ header.

   g++ -O2 -I. tools/dump_offsets.cpp hacks/schema.cpp -o /tmp/dump_offsets
   /tmp/dump_offsets > hacks/offsets.hpp
*/

#include <cstdio>

#include "hacks/schema.hpp"
#include "process.hpp"

namespace {

  struct Entry {
    const char *name;
    const char *class_name;
    const char *field;
    int fallback;
  };

  const Entry kEntries[] = {
      {"kPawnHandle", "CPlayer_WeaponServices", "m_hActiveWeapon", 0x60},
      {"kWeaponServices", "C_CSPlayerPawn", "m_pWeaponServices", 0x1278},
      {"kMyWeapons", "CPlayer_WeaponServices", "m_hMyWeapons", 0x48},
      {"kHealth", "C_CSPlayerPawn", "m_iHealth", 0x4BC},
      {"kTeam", "C_CSPlayerPawn", "m_iTeamNum", 0x557},
      {"kGameScene", "C_CSPlayerPawn", "m_pGameSceneNode", 0x4A0},
      {"kSimulationTime", "C_CSPlayerPawn", "m_flSimulationTime", 0x528},
      {"kViewAngles", "C_CSPlayerPawn", "m_angEyeAngles", 0x4490},
      {"kAimPunch", "C_CSPlayerPawn", "m_pAimPunchServices", 0x1520},
      {"kSpottedState", "C_CSPlayerPawn", "m_entitySpottedState", 0x2D10},
      {"kControllerHandle", "C_BasePlayerPawn", "m_hController", 0x13F4},
      {"kControllerName", "CBasePlayerController", "m_sSanitizedPlayerName", 0x9F8},
      {"kSceneOrigin", "CGameSceneNode", "m_vecAbsOrigin", 0xC8},
      {"kFallbackPaintKit", "C_EconEntity", "m_nFallbackPaintKit", 0x1178},
      {"kFallbackSeed", "C_EconEntity", "m_nFallbackSeed", 0x117C},
      {"kFallbackWear", "C_EconEntity", "m_flFallbackWear", 0x1180},
      {"kAttributesInitialized", "C_EconEntity", "m_bAttributesInitialized", 0xD38},
      {"kAttributeManager", "C_EconEntity", "m_AttributeManager", 0xD38},
      {"kItem", "C_AttributeContainer", "m_Item", 0x50},
      {"kEntityQuality", "C_EconItemView", "m_iEntityQuality", 0x10C4},
      {"kItemIdHigh", "C_EconItemView", "m_iItemIDHigh", 0x10DC},
      {"kItemIdLow", "C_EconItemView", "m_iItemIDLow", 0x10E0},
      {"kAttributeList", "C_EconItemView", "m_AttributeList", 0x1110},
      {"kAttributes", "CAttributeList", "m_Attributes", 0x08},
  };
}

int main() {
  const pid_t pid = Process::name_to_pid("cs2");
  if (!pid) {
    fprintf(stderr, "cs2 is not running\n");
    return 1;
  }

  if (!Schema::dump(pid)) {
    fprintf(stderr, "the schema could not be read: %s\n", Schema::status().c_str());
    return 1;
  }

  printf("/* Generated by tools/dump_offsets.cpp — do not edit by hand. */\n");
  printf("#ifndef FLER_OFFSETS_HPP\n#define FLER_OFFSETS_HPP\n\n");
  printf("namespace Offsets {\n\n");

  for (const Entry &entry : kEntries) {
    int value = Schema::offset(entry.class_name, entry.field);
    const bool found = value >= 0;
    if (!found) value = entry.fallback;
    printf("  /* %s::%s%s */\n", entry.class_name, entry.field, found ? "" : " (fallback)");
    printf("  constexpr int %s = 0x%X;\n", entry.name, value);
  }

  printf("\n} /* namespace Offsets */\n\n#endif\n");
  return 0;
}
